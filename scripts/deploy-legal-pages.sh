#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# deploy-legal-pages.sh — publish the legal pages in website/ to GitHub Pages.
#
# Target repo (public, so it can serve Pages). Override if it ever moves:
#   PAGES_REPO=some-org/some-repo ./scripts/deploy-legal-pages.sh
#
#   https://<owner>.github.io/<repo>/            <- home
#   https://<owner>.github.io/<repo>/privacy.html
#   https://<owner>.github.io/<repo>/terms.html
#
# How it works:
#   1. Adds a throwaway git worktree in a temp dir.
#   2. Rebuilds the `gh-pages` branch from scratch: it ends up containing
#      exactly the files from website/ (plus a .nojekyll so GitHub Pages
#      serves the assets/ subfolder without Jekyll processing).
#   3. Force-pushes that branch to the public target repo and probes the
#      live URLs.
#
# ⚠️  The `gh-pages` branch is fully generated by this script — never edit
#     files in it by hand; edit website/ and re-run.
#
# FIRST-RUN ONLY (one time, ~20 seconds):
#   After the first push, enable Pages once in the target repo's settings —
#   the script prints the exact deep link:
#     Settings → Pages → Build and deployment → Source: "Deploy from a
#     branch" → Branch: gh-pages, Folder: / (root) → Save
#   Every later run just updates the live site.
# ---------------------------------------------------------------------------

set -euo pipefail

PAGES_REPO="${PAGES_REPO:-octabytes-studio/quizoo}"
TARGET_URL="https://github.com/${PAGES_REPO}.git"
SSH_URL="git@github.com:${PAGES_REPO}.git"
# Optional: a PAT for the account that owns the target repo, if neither the
# keychain HTTPS credential nor SSH keys may push there. Never stored.
#   GITHUB_TOKEN=ghp_xxx ./scripts/deploy-legal-pages.sh
TOKEN_URL="https://x-access-token:${GITHUB_TOKEN:-}@github.com/${PAGES_REPO}.git"
BRANCH="gh-pages"

ROOT="$(git rev-parse --show-toplevel)"
SRC="$ROOT/website"

if [[ ! -d "$SRC" ]]; then
  echo "✗ $SRC not found — run this from inside the repository." >&2
  exit 1
fi

# Never touch gh-pages when it's the developer's currently placed branch.
current=$(git -C "$ROOT" symbolic-ref --short HEAD 2>/dev/null || true)
if [[ "$current" == "$BRANCH" ]]; then
  echo "✗ '$BRANCH' is checked out in the main worktree; switch to main first." >&2
  exit 1
fi

TMP="$(mktemp -d)"
cleanup() {
  git -C "$ROOT" worktree remove --force "$TMP" >/dev/null 2>&1 || true
  rm -rf "$TMP"
}
trap cleanup EXIT

# Pages URLs follow the target repo (owner part is lowercased by GitHub).
owner="${PAGES_REPO%%/*}"; repo="${PAGES_REPO##*/}"
pages_url="https://${owner}.github.io/${repo}"
settings_url="https://github.com/${owner}/${repo}/settings/pages"

echo "🦉  Publishing legal pages from website/ → ${BRANCH} of ${PAGES_REPO}"
git -C "$ROOT" worktree add --detach "$TMP" >/dev/null
cd "$TMP"

git switch -C "$BRANCH"                          # create or reset the branch
find . -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
cp -a "$SRC"/. .                                 # copy all page sources
touch .nojekyll                                  # let GitHub serve assets/ raw

git add -A
git commit -q -m "chore: publish Quizoo legal pages from website/ ($(date -u '+%Y-%m-%d %H:%M UTC'))"

# Push: HTTPS (keychain credential) → SSH (org access may key off SSH only)
# → token via GITHUB_TOKEN if you exported one. None stored by the script.
push_ok() { git push --force "$1" "$BRANCH"; }

if push_ok "$TARGET_URL" 2>"$TMP/push_http.log"; then
  :
elif push_ok "$SSH_URL" 2>"$TMP/push_ssh.log"; then
  :
elif [[ -n "${GITHUB_TOKEN:-}" ]] && push_ok "$TOKEN_URL" 2>"$TMP/push_tok.log"; then
  :
else
  cat "$TMP"/push*.log >&2 || true
  echo
  echo "✗  Push denied — none of HTTPS / SSH / GITHUB_TOKEN may write to ${PAGES_REPO}."
  echo "   Grant one of your accounts write access (Settings → Collaborators in"
  echo "   that repo), or run:  GITHUB_TOKEN=ghp_xxx $0"
  exit 1
fi
rm -f "$TMP"/push*.log
echo "✓  Pushed ${BRANCH} → ${PAGES_REPO} (branch contains only generated site files)."
echo
echo "Live URLs once Pages is enabled:"
echo "   • ${pages_url}/               (legal home)"
echo "   • ${pages_url}/privacy.html   (Privacy Policy)"
echo "   • ${pages_url}/terms.html     (Terms of Service)"

# Probe the site — during the very first run Pages is usually not enabled yet.
probe() {
  [[ -z "$(command -v curl)" ]] && return 0
  for _ in 1 2 3 4 5; do
    code=$(curl -s -o /dev/null -w '%{http_code}' "${pages_url}/privacy.html" || echo 000)
    if [[ "$code" == "200" ]]; then return 0; fi
    sleep 6
  done
  return 1
}
echo
if probe; then
  echo "✓  Site is live: ${pages_url}/privacy.html"
else
  echo "→  Site not responding yet — that's normal on the FIRST run: Pages is"
  echo "   disabled by default. Open this link once (repo settings):"
  echo
  echo "      ${settings_url}"
  echo
  echo "   Choose: Source → 'Deploy from a branch' · Branch: ${BRANCH} ·"
  echo "   Folder: / (root) → Save. Then re-run this script or just wait a   "
  echo "   minute; the URLs above will come alive by themselves."
fi
